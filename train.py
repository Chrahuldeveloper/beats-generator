class BeatGenerator(nn.Module):
    def __init__(self):
        super().__init__()

        self.network = nn.Sequential(
            nn.Linear(4, 128),
            nn.ReLU(),

            nn.Linear(128, 256),
            nn.ReLU(),

            nn.Linear(256, 832)
        )

    def forward(self, x):
        x = self.network(x)
        x = x.reshape(-1, 64, 13)
        return x

