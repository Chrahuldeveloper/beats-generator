import torch
import torch.nn as nn

class BeatRnn(nn.Module):

  def __init__(self):
    super().__init__()

    self.rnn = nn.RNN(
        input_size=13,
        batch_first=True,
        hidden_size=128,
        nonlinearity="tanh",
        num_layers=1
    )


    self.fc = nn.Linear(128,13)

  def forward(self,x):
    output,hidden = self.rnn(x)
    logits = self.fc(output)
    return logits

import json
from pathlib import Path
from torch.utils.data import Dataset


class BeatDataset(Dataset):

  def __init__(self, folder):
        self.files = sorted(
            Path(folder).glob("*.json")
        )

  def __len__(self):
    return len(self.files)


  def __getitem__(self,index):

    path = self.files[index]

    with open(path,"r") as f:
      data = json.load(f)

      pattern = torch.tensor(
        data,
        dtype=torch.float32
      )

      x = pattern[:-1]

      y = pattern[1:]

      return x, y

from torch.utils.data import DataLoader

dataset = BeatDataset("/content/drive/MyDrive/training")

loader = DataLoader(
    dataset,
    batch_size=32,
    shuffle=True
)


model = BeatRnn()


loss_fn = torch.nn.BCEWithLogitsLoss()

optimizer = torch.optim.Adam(
    model.parameters(),
    lr=0.001
)


epochs = 50


for epoch in range(epochs):

    model.train()
    total_loss = 0.0

    for x, y in loader:

        logits = model(x)

        loss = loss_fn(logits, y)

        optimizer.zero_grad()

        loss.backward()

        optimizer.step()

        total_loss += loss.item()

    average_loss = total_loss / len(loader)

    print(
        f"Epoch {epoch + 1}/{epochs} "
        f"Loss: {average_loss:.4f}"
    )


torch.save(model.state_dict(), "beat_rnn.pth")

print("Training complete!")
